def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for c in CASES:
        text = HEADER + yaml.safe_dump(c, sort_keys=False, allow_unicode=True, width=100)
        (OUT / f"{c['id']}.yaml").write_text(text, encoding="utf-8")
    print(f"wrote {len(CASES)} cases to {OUT}")


if __name__ == "__main__":
    main()
