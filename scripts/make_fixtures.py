def doc(case_id: str, doc_type: str) -> dict[str, str]:
    return {
        "doc_type": doc_type,
        "content": f"SPECIMEN - SYNTHETIC TEST DOCUMENT, NOT A REAL DOCUMENT\ncase={case_id}\ndoc_type={doc_type}\n",
    }


def field(
    name: str, value: str | None, conf: float, review: bool = False, reason: str | None = None
) -> dict[str, Any]:
    return {
        "name": name,
        "value": value,
        "confidence": conf,
        "needs_review": review,
        "reason": reason,
        "reviewed": False,
    }


def id_response(a: dict[str, Any], n: int, low: dict[str, float] | None = None) -> dict[str, Any]:
    low = low or {}
    vals = {
        "full_name": a["name"],
        "date_of_birth": a["dob"],
        "id_number": f"SPEC-ID-{n:04d}",
        "nationality": a["nationality"],
        "expiry_date": "2031-05-14",
        "issuing_country": a["nationality"],
    }
    fields = []
    for k, v in vals.items():
        if k in low:
            fields.append(field(k, v, low[k], True, "low_confidence"))
        else:
            fields.append(field(k, v, 0.97))
    flagged = any(f["needs_review"] for f in fields)
    return {
        "document_type": "id_document",
        "status": "needs_review" if flagged else "extracted",
        "needs_review": flagged,
        "fields": fields,
    }


def poa_response(a: dict[str, Any], city: str) -> dict[str, Any]:
    fields = [
        field("full_name", a["name"], 0.96),
        field("address_line", "SPECIMEN Street 1", 0.93),
        field("city", city, 0.95),
        field("issue_date", "2026-08-31", 0.97),
        field("issuer", "SPECIMEN Utility Co", 0.94),
    ]
    return {
        "document_type": "proof_of_address",
        "status": "extracted",
        "needs_review": False,
        "fields": fields,
    }


def case(
    cid: str,
    desc: str,
    a: dict[str, Any],
    n: int,
    city: str,
    expected: dict[str, Any],
    script: list[dict[str, Any]],
    *,
    docs: tuple[str, ...] = ("id_document", "proof_of_address"),
    followup: tuple[str, ...] = (),
    low: dict[str, float] | None = None,
    kyc: str = "ok",
    llm: str = "ok",
) -> dict[str, Any]:
    responses: dict[str, Any] = {}
    if kyc == "ok":
        responses = {"id_document": id_response(a, n, low), "proof_of_address": poa_response(a, city)}
    return {
        "id": cid,
        "specimen": True,
        "description": desc,
        "applicant": a,
        "documents": [doc(cid, t) for t in docs],
        "followup_documents": [doc(cid, t) for t in followup],
        "kyc_mode": kyc,
        "llm_mode": llm,
        "kyc_response": responses,
        "human_script": script,
        "expected": expected,
    }


def app(
    name: str, dob: str, nat: str, res: str, occ: str, aliases: list[str] | None = None
) -> dict[str, Any]:
    return {
        "name": name,
        "aliases": aliases or [],
        "dob": dob,
        "nationality": nat,
        "residence_country": res,
        "occupation": occ,
    }


def exp(
    rec: str,
    rating: str,
    final: str,
    traj: list[str],
    *,
    hits: list[dict[str, str]] | None = None,
    rules: list[str] | None = None,
    degraded: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "recommendation": rec,
        "risk_rating": rating,
        "hits": hits or [],
        "fired_rules": rules or [],
        "final_status": final,
        "degraded": degraded or [],
        "trajectory": traj,
        "required_steps": REQ,
    }


